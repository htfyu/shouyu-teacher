export function detectDomain(course, major, group, department) {
  const courseText = [course?.name, course?.category].filter(Boolean).join(" ");
  const contextText = [
    major?.name,
    major?.trainingGoal,
    major?.coreAbilities,
    group?.name,
    department?.name
  ].filter(Boolean).join(" ");
  // Course name wins over a major's broad industry wording. For example,
  // 机电一体化技术的培养目标会提到汽车行业，但“电工技术”仍应使用电气模板。
  for (const [domain, pattern] of DOMAIN_RULES) {
    if (pattern.test(courseText)) return domain;
  }
  for (const [domain, pattern] of DOMAIN_RULES) {
    if (pattern.test(contextText)) return domain;
  }
  return "general";
}

