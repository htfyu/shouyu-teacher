export function getDoc(id) {
  return KB_DOCS.find((doc) => doc.id === id) || null;
}

export function getSection(docId, sectionId) {
  const doc = getDoc(docId);
  return doc ? doc.sections.find((s) => s.id === sectionId) || null : null;
}

export function totalSections() {
  return KB_DOCS.reduce((sum, doc) => sum + doc.sections.length, 0);
}

export function docMarkdown(doc) {
  const lines = [
    `# ${doc.title}`,
    "",
    `- 知识库编号：${doc.id}`,
    `- 分类：${doc.category}`,
    doc.specialty ? `- 所属专业：${doc.specialty}` : "",
    doc.course ? `- 所属课程：${doc.course}` : "",
    `- 来源：${doc.source || "校本示例 · 教学团队整理"}`,
    `- 作者 / 单位：${doc.author || "匠备教研示例"}`,
    doc.published ? `- 发布时间：${doc.published}` : "",
    `- 版本：${doc.version}`,
    `- 更新：${doc.updated}`,
    `- 标签：${(doc.tags || []).join("、")}`,
    "",
    `> ${doc.summary}`,
    "",
    doc.scope ? `> 适用范围：${doc.scope}` : "",
    doc.builtin ? "> 说明：本材料为「匠备」演示用校本示例，不对应任何正式文件。正式使用前请替换为学院现行制度并由负责人审核。" : "> 说明：本材料由教师在本机自建 / 导入，未经学校审核；正式使用前请核对原文与现行制度。",
    ""
  ].filter((line) => line !== "");
  doc.sections.forEach((section) => {
    lines.push(`## ${section.no} ${section.title}`, "", section.text, "");
    (section.bullets || []).forEach((bullet) => lines.push(`- ${bullet}`));
    lines.push("");
  });
  return lines.join("\n");
}